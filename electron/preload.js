const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  platform: process.platform,
  mediaUrl: (p) => 'app://media/' + encodeURIComponent(p),
  getPathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch (_) { return ''; } },
  openMedia: () => ipcRenderer.invoke('dialog:openMedia'),
  openProjectDialog: () => ipcRenderer.invoke('dialog:openProject'),
  saveProjectDialog: (name) => ipcRenderer.invoke('dialog:saveProject', name),
  saveExportDialog: (o) => ipcRenderer.invoke('dialog:saveExport', o),
  chooseFolder: () => ipcRenderer.invoke('dialog:chooseFolder'),
  readText: (p) => ipcRenderer.invoke('fs:readText', p),
  writeText: (p, t) => ipcRenderer.invoke('fs:writeText', p, t),
  writeBinary: (p, b) => ipcRenderer.invoke('fs:writeBinary', p, b),
  exists: (p) => ipcRenderer.invoke('fs:exists', p),
  autosaveLoad: () => ipcRenderer.invoke('autosave:load'),
  autosaveSave: (t) => ipcRenderer.invoke('autosave:save', t),
  showItem: (p) => ipcRenderer.invoke('shell:showItem', p),
  openPath: (p) => ipcRenderer.invoke('shell:openPath', p),
  info: () => ipcRenderer.invoke('app:info'),
  probe: (p) => ipcRenderer.invoke('media:probe', p),
  proxy: (p, id) => ipcRenderer.invoke('media:proxy', p, id),
  onProxyProgress: (cb) => ipcRenderer.on('media:proxyProgress', (_e, id, v) => cb(id, v)),
  waveform: (p) => ipcRenderer.invoke('media:waveform', p),
  exportStart: (o) => ipcRenderer.invoke('export:start', o),
  exportFrame: (buf) => ipcRenderer.invoke('export:frame', buf),
  exportFinish: () => ipcRenderer.invoke('export:finish'),
  exportCancel: () => ipcRenderer.invoke('export:cancel'),
  exportAudio: (o) => ipcRenderer.invoke('export:audio', o),
  onAudioProgress: (cb) => { ipcRenderer.removeAllListeners('export:audioProgress'); ipcRenderer.on('export:audioProgress', (_e, v) => cb(v)); },
  // collaboration
  collabHost: (o) => ipcRenderer.invoke('collab:host', o),
  collabJoin: (o) => ipcRenderer.invoke('collab:join', o),
  collabLeave: () => ipcRenderer.invoke('collab:leave'),
  collabSend: (m) => ipcRenderer.invoke('collab:send', m),
  collabProvideState: (id, s) => ipcRenderer.invoke('collab:provideState', id, s),
  collabRegisterMedia: (id, p) => ipcRenderer.invoke('collab:registerMedia', id, p),
  collabUpload: (o) => ipcRenderer.invoke('collab:upload', o),
  collabFetchMedia: (o) => ipcRenderer.invoke('collab:fetchMedia', o),
  collabDiscoverStart: () => ipcRenderer.invoke('collab:discoverStart'),
  collabDiscoverStop: () => ipcRenderer.invoke('collab:discoverStop'),
  collabInfo: () => ipcRenderer.invoke('collab:info'),
  onCollab: (ch, cb) => ipcRenderer.on('collab:' + ch, (_e, ...a) => cb(...a)),
  // sharing
  sharePack: (o) => ipcRenderer.invoke('share:pack', o),
  shareSaveDialog: (n) => ipcRenderer.invoke('share:saveDialog', n),
  shareOpenDialog: () => ipcRenderer.invoke('share:openDialog'),
  shareUnpack: (p) => ipcRenderer.invoke('share:unpack', p),
  onShareProgress: (cb) => { ipcRenderer.removeAllListeners('share:progress'); ipcRenderer.on('share:progress', (_e, v) => cb(v)); },
  onOpenFile: (cb) => ipcRenderer.on('app:openFile', (_e, f) => cb(f)),
  pendingOpen: () => ipcRenderer.invoke('app:pendingOpen'),
  presetsLoad: () => ipcRenderer.invoke('presets:load'),
  presetsSave: (t) => ipcRenderer.invoke('presets:save', t),
  presetsExportDialog: (n) => ipcRenderer.invoke('presets:exportDialog', n),
  presetsImportDialog: () => ipcRenderer.invoke('presets:importDialog'),
  recSave: (o) => ipcRenderer.invoke('rec:save', o),
  recentsLoad: () => ipcRenderer.invoke('recents:load'),
  recentsSave: (l) => ipcRenderer.invoke('recents:save', l),
  decOpen: (o) => ipcRenderer.invoke('dec:open', o),
  decNext: (k, skip) => ipcRenderer.invoke('dec:next', k, skip),
  decClose: (k) => ipcRenderer.invoke('dec:close', k),
});
